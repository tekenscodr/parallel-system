/**
 * Builds a SQL WHERE condition fragment for filtering TESCON executives by institution.
 */
export function buildTesconInstitutionCondition(
  sql: any,
  institution: string,
  region?: string | null
) {
  if (!institution || !institution.trim()) return null;
  const inst = institution.trim();
  const regKey = region ? region.trim().toLowerCase() : "";

  const aliasSet = new Set<string>();
  aliasSet.add(inst);

  // If a region is specified, look up in that region first
  if (regKey) {
    for (const [r, mapping] of Object.entries(CANONICAL_TO_RAW_STATIONS_BY_REGION)) {
      if (r.toLowerCase() === regKey && mapping[inst]) {
        for (const a of mapping[inst]) aliasSet.add(a);
      }
    }
  } else {
    for (const mapping of Object.values(CANONICAL_TO_RAW_STATIONS_BY_REGION)) {
      if (mapping[inst]) {
        for (const a of mapping[inst]) aliasSet.add(a);
      }
    }
  }

  const aliases = Array.from(aliasSet).filter((a) => Boolean(a && a.trim()));

  return sql`(
    polling_station = ${inst}
    OR polling_station ILIKE ${"%" + inst + "%"}
    ${aliases.length > 0 ? sql`OR polling_station IN ${sql(aliases)}` : sql``}
  )`;
}
