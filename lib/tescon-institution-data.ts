/**
 * Returns accredited tertiary institutions for a specific region,
 * or all institutions if region is empty or "all".
 */
export function getTesconInstitutionsForRegion(region?: string | null): string[] {
  if (!region || region.trim().toLowerCase() === "all" || region.trim() === "") {
    return ALL_CANONICAL_TESCON_INSTITUTIONS;
  }
  const cleanReg = region.trim().toLowerCase();
  for (const [r, list] of Object.entries(CANONICAL_TESCON_INSTITUTIONS_BY_REGION)) {
    if (r.toLowerCase() === cleanReg) {
      return list;
    }
  }
  return [];
}

